-- CRIANDO A TABELA CLIENTE

DROP TABLE CLIENTE CASCADE CONSTRAINTS;

CREATE TABLE CLIENTE (
    CODIGO  NUMBER  CONSTRAINT PK_CLIENTE   PRIMARY KEY,
    NOME    varchar2(60) NOT NULL,
    RUA     varchar2(80)    NOT NULL,
    NR      NUMBER(4)   NOT NULL,
    BAIRRO  varchar2(50)    NOT NULL,
    COMPLEMENTO varchar2(100)   NULL,
    CIDADE  varchar2(50)    NOT NULL,
    UF  varchar2(2)    NOT NULL,
    CEP varchar2(10)    NOT NULL
);



-- CRIANDO A TABELA VENDEDOR

DROP TABLE VENDEDOR CASCADE CONSTRAINTS;

CREATE TABLE VENDEDOR (
    MATRICULA   NUMBER  CONSTRAINT PK_VENDEDOR PRIMARY KEY,
    NOME    varchar2(60)    NOT NULL,
    CNPF    varchar2(14)    NOT NULL
);



-- CRIANDO A TABELA PEDIDO

DROP TABLE PEDIDO CASCADE CONSTRAINTS;

CREATE TABLE PEDIDO (
    NUMERO  NUMBER(6)   CONSTRAINT PK_PEDIDO PRIMARY KEY,
    DATA    DATE    NOT NULL,
    PRAZO_ENTREGA   DATE    NULL,
    RUA     varchar2(80)    NULL,
    NR      NUMBER(4)   NULL,
    BAIRRO  varchar2(50)    NULL,
    COMPLEMENTO     varchar2(100)    NULL,
    CIDADE      varchar2(50)    NULL,
    UF      varchar2(2)    NULL,
    CEP     varchar2(10)    NULL,
    TOTAL_FATURA    NUMBER(8,2)     NULL,
    CODIGO_CLI      NUMBER  CONSTRAINT FK_PED_CLIENTE REFERENCES CLIENTE(CODIGO),
    MATRICULA_VEN   NUMBER  CONSTRAINT FK_PED_VENDEDOR REFERENCES VENDEDOR(MATRICULA)
);



-- CRIANDO A TABELA PRODUTO

DROP TABLE PRODUTO CASCADE CONSTRAINTS;

CREATE TABLE PRODUTO (
    CODIGO  NUMBER  ,
    DESCRICAO   varchar2(80)    NOT NULL,
    UNID_MEDIDA varchar2(10)    NOT NULL,

    CONSTRAINT PK_PRODUTO PRIMARY KEY (CODIGO)
);



-- CRIANDO A TABELA PRATELEIRA

DROP TABLE PRATELEIRA CASCADE CONSTRAINTS;

CREATE TABLE PRATELEIRA (
    CODIGO  NUMBER(3)   CONSTRAINT PK_PRATELEIRA PRIMARY KEY,
    DESCRICAO   varchar2(50)    NOT NULL,
    NUMERO_SECOES   NUMBER(2)   NOT NULL
);



-- CRIANDO A TABELA FONE_CLIENTE

DROP TABLE FONE_CLIENTE CASCADE CONSTRAINTS;

CREATE TABLE FONE_CLIENTE (
    NUMERO  varchar2(14)    ,
    CODIGO_CLI  NUMBER   ,
    
    CONSTRAINT PK_FONE_CLIENTE PRIMARY KEY (NUMERO, CODIGO_CLI),
    CONSTRAINT FK_FONE_CLIENTE FOREIGN KEY (CODIGO_CLI) REFERENCES CLIENTE(CODIGO)
);



-- CRIANDO A TABELA FONE_VENDEDOR

DROP TABLE FONE_VENDEDOR CASCADE CONSTRAINTS;

CREATE TABLE FONE_VENDEDOR (
    NUMERO  varchar2(14)    ,
    MATRICULA_VEN  NUMBER   ,
    
    CONSTRAINT PK_FONE_VENDEDOR PRIMARY KEY (NUMERO, MATRICULA_VEN),
    CONSTRAINT FK_FONE_VENDEDOR FOREIGN KEY (MATRICULA_VEN) REFERENCES VENDEDOR(MATRICULA)
);



-- CRIANDO A TABELA PF

DROP TABLE PF CASCADE CONSTRAINTS;

CREATE TABLE PF (
    CODIGO_CLI  NUMBER  ,
    CNPF    varchar2(14)    NOT NULL,
    RG      varchar2(10)    NOT NULL,
    DATA_NASCIMENTO DATE    NOT NULL,
    
    CONSTRAINT PK_CLIENTE_PF PRIMARY KEY (CODIGO_CLI),
    CONSTRAINT FK_PF_CLIENTE FOREIGN KEY (CODIGO_CLI) REFERENCES CLIENTE(CODIGO)
);



-- CRIANDO A TABELA PJ

DROP TABLE PJ CASCADE CONSTRAINTS;

CREATE TABLE PJ (
    CODIGO_CLI  NUMBER  ,
    CNPJ    varchar2(19)    NOT NULL,
    IE      varchar2(10)    NOT NULL,
    NOME_FANTASIA varchar2(60)    NOT NULL,
    
    CONSTRAINT PK_CLIENTE_PJ PRIMARY KEY (CODIGO_CLI),
    CONSTRAINT FK_PJ_CLIENTE FOREIGN KEY (CODIGO_CLI) REFERENCES CLIENTE(CODIGO)
);



-- CRIANDO A TABELA ITEM_PRODUTO

DROP TABLE ITEM_PRODUTO CASCADE CONSTRAINTS;

CREATE TABLE ITEM_PRODUTO (
    CODIGO_PRO  NUMBER  ,
    NUMERO_PED  NUMBER(6),
    QUANTIDADE  NUMBER(5)   NOT NULL,
    PRECO_UNITARIO  NUMBER(5,2) NOT NULL,
    VALOR_ITEM  NUMBER(7,2) NULL,

    CONSTRAINT PK_ITEM_PRODUTO PRIMARY KEY (CODIGO_PRO, NUMERO_PED),
    CONSTRAINT FK_ITEM_PRODUTO FOREIGN KEY (CODIGO_PRO) REFERENCES PRODUTO(CODIGO),
    CONSTRAINT FK_ITEM_PEDIDO FOREIGN KEY (NUMERO_PED) REFERENCES PEDIDO(NUMERO)
);



-- CRIANDO A TABELA ESTOQUE

DROP TABLE ESTOQUE CASCADE CONSTRAINTS;

CREATE TABLE ESTOQUE (
    DATA_ENTRADA    DATE    ,
    CODIGO_PRO  NUMBER  ,
    CODIGO_PRA  NUMBER(3)   ,
    QUANTIDADE  NUMBER(5)   NOT NULL,
    DATA_VALIDADE   DATE    NULL,

    CONSTRAINT PK_ESTOQUE PRIMARY KEY (DATA_ENTRADA, CODIGO_PRO, CODIGO_PRA),
    CONSTRAINT FK_EST_PRODUTO FOREIGN KEY (CODIGO_PRO) REFERENCES PRODUTO(CODIGO),
    CONSTRAINT FK_EST_PRATELEIRA FOREIGN KEY (CODIGO_PRA) REFERENCES PRATELEIRA(CODIGO)
);



-- CRIANDO A TABELA CAPACIDADE_ESTOQUE

DROP TABLE CAPACIDADE_ESTOQUE CASCADE CONSTRAINTS;

CREATE TABLE CAPACIDADE_ESTOQUE (
    CODIGO_PRO  NUMBER  ,
    CODIGO_PRA  NUMBER(3)   ,
    QUANTIDADE  NUMBER(5)   NOT NULL,

    CONSTRAINT PK_CAPACIDADE_ESTOQUE PRIMARY KEY (CODIGO_PRO, CODIGO_PRA),
    CONSTRAINT FK_CAP_EST_PRODUTO FOREIGN KEY (CODIGO_PRO) REFERENCES PRODUTO(CODIGO),
    CONSTRAINT FK_CAP_EST_PRATELEIRA FOREIGN KEY (CODIGO_PRA) REFERENCES PRATELEIRA(CODIGO)
);


