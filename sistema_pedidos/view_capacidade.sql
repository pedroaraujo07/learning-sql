-- a. Criar a view que mostra a capacidade de estoque constante no BD
-- Pedidos. (VIEW_CAPACIDADE_ESTOQUE) contendo os dados indicados no
-- modelo apresentado.
-- RESOLUÇÃO:

CREATE OR REPLACE VIEW VIEW_CAPACIDADE_ESTOQUE AS
SELECT 
    P.DESCRICAO AS PRODUTO,
    PR.DESCRICAO AS PRATELEIRA,
    CE.QUANTIDADE,
    P.UNID_MEDIDA AS UNIDADE_MEDIDA
FROM CAPACIDADE_ESTOQUE CE
JOIN PRODUTO P ON CE.CODIGO_PRO = P.CODIGO
JOIN PRATELEIRA PR ON CE.CODIGO_PRA = PR.CODIGO;

SELECT * FROM VIEW_CAPACIDADE_ESTOQUE;