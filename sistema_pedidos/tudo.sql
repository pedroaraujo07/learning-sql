    P.NUMERO AS PEDIDO,
    TO_CHAR(P.DATA, 'DD/MM/YYYY') AS DATA
FROM VENDEDOR V
JOIN PEDIDO P ON V.MATRICULA = P.MATRICULA_VEN
WHERE P.TOTAL_FATURA BETWEEN 1000.00 AND 5000.00
ORDER BY VENDEDOR DESC, P.DATA ASC;





