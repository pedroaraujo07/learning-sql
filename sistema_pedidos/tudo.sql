CREATE OR REPLACE VIEW VIEW_CLIENTE AS
SELECT 
    C.CODIGO,
    C.NOME,
    C.RUA,
    C.NR,
    C.BAIRRO,
    C.COMPLEMENTO,
    C.CIDADE,
    C.UF,
    C.CEP,
    CASE 
        WHEN PF.CODIGO_CLI IS NOT NULL THEN 'PF'
        WHEN PJ.CODIGO_CLI IS NOT NULL THEN 'PJ'
        ELSE 'INDEFINIDO'
    END AS TIPO_CLIENTE,
